'use client';

import { useEffect, useRef, useState, useSyncExternalStore } from 'react';
import Link from 'next/link';
import {
  Check,
  Copy,
  Download,
  ExternalLink,
  KeyRound,
  Share2,
  X,
} from 'lucide-react';
import { setupDialogLightDismiss } from '@/lib/polyfills/ui';

export interface PublishedEventResult {
  id: string;
  editKey: string;
  title: string;
  startIso?: string;
  timeZone?: string;
  locationName?: string;
  themeId?: string;
}

interface PublishSuccessDialogProps {
  published: PublishedEventResult | null;
  onClose: () => void;
}

export function downloadLinksBackupTxt(params: {
  title: string;
  guestUrl: string;
  editUrl: string;
  startIso?: string;
  timeZone?: string;
}): void {
  const safeSlug =
    params.title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .slice(0, 48) || 'event';

  const lines = [
    `EVENT: ${params.title}`,
    params.startIso ? `WHEN: ${params.startIso} (${params.timeZone ?? 'local'})` : '',
    '',
    'GUEST INVITE LINK (share with friends):',
    params.guestUrl,
    '',
    'SECRET HOST EDIT LINK (save safely — acts as your admin key):',
    params.editUrl,
    '',
    'Generated by Invited',
  ]
    .filter((line, idx, arr) => !(line === '' && arr[idx - 1] === ''))
    .join('\n');

  const blob = new Blob([lines], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = `${safeSlug}-links.txt`;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

const subscribeNoop = () => () => {};

export function PublishSuccessDialog({
  published,
  onClose,
}: PublishSuccessDialogProps) {
  const dialogRef = useRef<HTMLDialogElement>(null);
  const origin = useSyncExternalStore(
    subscribeNoop,
    () => window.location.origin,
    () => '',
  );
  const [copiedWhich, setCopiedWhich] = useState<'guest' | 'edit' | null>(null);
  const [shareFeedback, setShareFeedback] = useState<string | null>(null);

  useEffect(() => {
    const dialog = dialogRef.current;
    if (!dialog) return;

    const cleanupDismiss = setupDialogLightDismiss(dialog);
    const handleClose = () => {
      onClose();
    };
    dialog.addEventListener('close', handleClose);
    return () => {
      cleanupDismiss();
      dialog.removeEventListener('close', handleClose);
    };
  }, [onClose]);

  useEffect(() => {
    const dialog = dialogRef.current;
    if (!dialog) return;
    if (published && !dialog.open) {
      dialog.showModal();
    } else if (!published && dialog.open) {
      dialog.close();
    }
  }, [published]);

  const guestPath = published ? `/e/${published.id}` : '';
  const editPath = published
    ? `/e/${published.id}/edit?key=${encodeURIComponent(published.editKey)}`
    : '';
  const fullGuestUrl = origin && guestPath ? `${origin}${guestPath}` : guestPath;
  const fullEditUrl = origin && editPath ? `${origin}${editPath}` : editPath;

  const copyText = async (which: 'guest' | 'edit', value: string) => {
    if (!value) return;
    try {
      await navigator.clipboard.writeText(value);
      setCopiedWhich(which);
      window.setTimeout(() => {
        setCopiedWhich((prev) => (prev === which ? null : prev));
      }, 2200);
    } catch {
      // Clipboard fallback not needed; URLs remain selectable
    }
  };

  const handleWebShare = async () => {
    if (!published || !fullGuestUrl) return;
    if (typeof navigator !== 'undefined' && typeof navigator.share === 'function') {
      try {
        await navigator.share({
          title: published.title,
          text: `You're invited to ${published.title}`,
          url: fullGuestUrl,
        });
        return;
      } catch {
        // Ignore user cancel
      }
    }
    await copyText('guest', fullGuestUrl);
    setShareFeedback('Guest link copied.');
    window.setTimeout(() => setShareFeedback(null), 2200);
  };

  return (
    <dialog
      ref={dialogRef}
      closedby="any"
      aria-labelledby="publish-success-heading"
      className="m-auto w-[calc(100%-2rem)] max-w-md rounded-2xl border border-white/15 bg-slate-950/95 text-slate-100 p-5 shadow-2xl backdrop:bg-black/65 backdrop:backdrop-blur-sm"
    >
      {published ? (
        <div className="space-y-4">
          <div className="flex items-start justify-between gap-3">
            <div className="min-w-0">
              <p className="text-xs font-medium text-emerald-300">Ready to share</p>
              <h2
                id="publish-success-heading"
                className="text-lg font-bold text-white leading-snug mt-0.5 truncate"
              >
                {published.title}
              </h2>
            </div>

            <button
              type="button"
              onClick={onClose}
              aria-label="Close publish dialog"
              className="h-8 w-8 rounded-full border border-white/15 flex items-center justify-center text-slate-300 hover:bg-white/10 shrink-0 cursor-pointer"
            >
              <X className="h-4 w-4" aria-hidden="true" />
            </button>
          </div>

          {/* Guest Invite Link */}
          <div className="rounded-xl border border-white/12 bg-white/[0.04] p-3.5 space-y-2.5">
            <p className="text-xs font-medium text-slate-300">Guest Invite Link</p>
            <div className="rounded-lg border border-white/10 bg-slate-900/90 px-3 py-2 font-mono text-xs text-slate-200 break-all select-all">
              {fullGuestUrl}
            </div>
            <div className="flex flex-wrap gap-2">
              <button
                type="button"
                onClick={() => void copyText('guest', fullGuestUrl)}
                className="flex-1 inline-flex items-center justify-center gap-1.5 rounded-xl bg-white px-3.5 py-2 text-xs sm:text-sm font-semibold text-slate-950 hover:bg-slate-100 transition cursor-pointer"
              >
                {copiedWhich === 'guest' ? (
                  <>
                    <Check className="h-3.5 w-3.5" aria-hidden="true" />
                    <span>Copied</span>
                  </>
                ) : (
                  <>
                    <Copy className="h-3.5 w-3.5" aria-hidden="true" />
                    <span>Copy Link</span>
                  </>
                )}
              </button>

              <button
                type="button"
                onClick={() => void handleWebShare()}
                className="inline-flex items-center justify-center gap-1.5 rounded-xl border border-white/15 px-3 py-2 text-xs sm:text-sm font-medium text-white hover:bg-white/10 transition cursor-pointer"
              >
                <Share2 className="h-3.5 w-3.5" aria-hidden="true" />
                <span>Share</span>
              </button>

              <Link
                href={guestPath}
                className="inline-flex items-center justify-center gap-1.5 rounded-xl border border-white/15 px-3 py-2 text-xs sm:text-sm font-medium text-white hover:bg-white/10 transition"
              >
                <span>Open</span>
                <ExternalLink className="h-3.5 w-3.5" aria-hidden="true" />
              </Link>
            </div>
            {shareFeedback ? (
              <p className="text-xs text-emerald-300">{shareFeedback}</p>
            ) : null}
          </div>

          {/* Secret Host Edit Link */}
          <div className="rounded-xl border border-amber-300/25 bg-amber-500/[0.06] p-3.5 space-y-2.5">
            <div className="flex items-center justify-between gap-2">
              <span className="inline-flex items-center gap-1.5 text-xs font-medium text-amber-200">
                <KeyRound className="h-3.5 w-3.5" aria-hidden="true" />
                <span>Secret Host Edit Link</span>
              </span>
              <span className="text-[11px] text-amber-200/75">Keep private</span>
            </div>

            <div className="rounded-lg border border-amber-300/20 bg-slate-950/75 px-3 py-2 font-mono text-xs text-amber-100 break-all select-all">
              {fullEditUrl}
            </div>

            <div className="flex flex-wrap gap-2">
              <button
                type="button"
                onClick={() => void copyText('edit', fullEditUrl)}
                className="inline-flex items-center gap-1.5 rounded-xl bg-amber-300 px-3 py-2 text-xs font-semibold text-slate-950 hover:bg-amber-200 transition cursor-pointer"
              >
                {copiedWhich === 'edit' ? (
                  <>
                    <Check className="h-3.5 w-3.5" aria-hidden="true" />
                    <span>Copied</span>
                  </>
                ) : (
                  <>
                    <Copy className="h-3.5 w-3.5" aria-hidden="true" />
                    <span>Copy Edit Link</span>
                  </>
                )}
              </button>

              <button
                type="button"
                onClick={() =>
                  downloadLinksBackupTxt({
                    title: published.title,
                    guestUrl: fullGuestUrl,
                    editUrl: fullEditUrl,
                    startIso: published.startIso,
                    timeZone: published.timeZone,
                  })
                }
                className="inline-flex items-center gap-1.5 rounded-xl border border-amber-300/35 px-3 py-2 text-xs font-medium text-amber-100 hover:bg-amber-400/15 transition cursor-pointer"
              >
                <Download className="h-3.5 w-3.5" aria-hidden="true" />
                <span>Save .txt</span>
              </button>

              <Link
                href={editPath}
                className="inline-flex items-center gap-1.5 rounded-xl border border-white/15 px-3 py-2 text-xs font-medium text-white hover:bg-white/10 transition"
              >
                <span>Manage</span>
              </Link>
            </div>
          </div>
        </div>
      ) : null}
    </dialog>
  );
}
